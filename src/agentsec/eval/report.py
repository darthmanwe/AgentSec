"""Generate the README's results section from a published artifact (AS-040).

The README has claimed since the first Axis-B run that its number is "generated from a
committed evaluation artifact". It was not. ``git ls-files eval/`` returned only the
preregistration lock, ``eval/artifacts/`` is gitignored, and the number had been
transcribed by hand — correctly, as it happens, which is exactly why nobody noticed. A
claim about provenance that nothing enforces is a claim about intent.

So this module does three things, and refuses rather than warns at each of them:

1. **Publishes** an artifact into ``eval/results/published/``, which is whitelisted in
   ``.gitignore`` precisely so evidence can be committed deliberately while exploratory
   runs are not.
2. **Renders** the results section from that artifact, copying the headline sentence
   verbatim. The runner generates that sentence from its own counters so it cannot drift
   into "proven zero rate"; re-deriving it here would reintroduce the second source of
   truth the runner exists to prevent.
3. **Checks**, in CI, that the README still matches the published artifact and that the
   artifact is tracked by git. A README that has drifted from its evidence is worse than
   one with no number in it.

An artifact that is not ``reportable`` is refused outright. That is the whole mechanism:
a dry run, a smoke run, a partial run and a run whose preregistered inputs drifted all
carry ``reportable: false``, and none of them may become the published number.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import pathlib
import subprocess
from typing import Any, Final

REPO_ROOT: Final = pathlib.Path(__file__).resolve().parents[3]
PUBLISHED_DIR: Final = REPO_ROOT / "eval" / "results" / "published"
README_PATH: Final = REPO_ROOT / "README.md"

BEGIN: Final = "<!-- BEGIN GENERATED: eval-results -->"
END: Final = "<!-- END GENERATED: eval-results -->"

#: Written into the block so a reader knows not to hand-edit it, and so a diff that
#: touches it is obviously a regeneration rather than a rewrite.
PREAMBLE: Final = (
    "<!-- Generated by `uv run task report`. Do not edit by hand; edit the artifact's "
    "run instead. -->"
)


class ReportError(Exception):
    """The report cannot be produced, or the README has drifted from its evidence."""


# --------------------------------------------------------------------------- loading


def display(path: pathlib.Path) -> str:
    """Repo-relative when possible, bare name otherwise.

    A path outside the tree is not an error worth raising over — it is what a test
    fixture or a one-off artifact looks like — and a renderer that crashed on one would be
    untestable without writing into the repository.
    """
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.name


def digest_of(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_artifact(path: pathlib.Path) -> dict[str, Any]:
    """Read an artifact and refuse it unless it is fit to publish."""
    try:
        document: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ReportError(f"{path}: cannot read artifact: {error}") from error

    if not document.get("reportable"):
        notes = "; ".join(str(note) for note in document.get("notes", ())) or "no reason recorded"
        raise ReportError(
            f"{path.name} is not reportable, so it cannot become the published number. "
            f"Reason: {notes}"
        )
    if not document.get("complete"):
        raise ReportError(f"{path.name} is incomplete; resume it before publishing.")
    if document.get("drifted_inputs"):
        raise ReportError(
            f"{path.name} ran against drifted inputs {document['drifted_inputs']}; it is a "
            f"different experiment and needs its own preregistration."
        )
    return document


def latest_published() -> pathlib.Path:
    candidates = sorted(PUBLISHED_DIR.glob("*.json"))
    if not candidates:
        raise ReportError(
            f"nothing published yet. Run `--publish <artifact>` to place one in "
            f"{display(PUBLISHED_DIR)}."
        )
    return candidates[-1]


def is_tracked(path: pathlib.Path) -> bool:
    """Whether git has this file.

    The README says the number comes from a *committed* artifact. Nothing but this makes
    that true.
    """
    try:
        result = subprocess.run(  # noqa: S603 - fixed argv, no shell
            ["git", "ls-files", "--error-unmatch", str(path)],  # noqa: S607
            cwd=REPO_ROOT,
            capture_output=True,
            check=False,
        )
    except OSError:
        return False
    return result.returncode == 0


# --------------------------------------------------------------------------- rendering


def _fraction(numerator: int, denominator: int) -> str:
    if not denominator:
        return "—"
    return f"{numerator}/{denominator} ({numerator / denominator:.0%})"


def _axis_b_table(cells: list[dict[str, Any]]) -> list[str]:
    rows = [cell for cell in cells if cell.get("planner") == "adversarial"]
    if not rows:
        return []
    lines = [
        "",
        "**Axis B — the control-plane guarantee.** A deterministic planner that is already",
        "fully compromised, emitting the attacker's desired plan directly.",
        "",
        "| Controls | Trials | Unauthorized attempts | Executions | Reached a backend |",
        "|---|---:|---:|---:|---:|",
    ]
    for cell in sorted(rows, key=lambda row: str(row.get("controls", ""))):
        score = cell.get("authorization") or {}
        lines.append(
            f"| `{cell.get('controls', '?')}` "
            f"| {score.get('trials', 0)} "
            f"| {score.get('unauthorized_attempts', 0)} "
            f"| **{score.get('unauthorized_executions', 0)}** "
            f"| {score.get('attempts_reaching_a_backend', 0)} |"
        )
    return lines


def _axis_a_table(cells: list[dict[str, Any]]) -> list[str]:
    rows = [cell for cell in cells if cell.get("planner") == "real"]
    if not rows:
        return [
            "",
            "**Axis A — model susceptibility.** Not run. It is the only part that costs money.",
        ]

    lines = [
        "",
        "**Axis A — model susceptibility.** A real model against the template-aware and",
        "multi-turn injection corpus, through the same control path.",
        "",
        "| Controls | Cases | Proposed the canary | Executed it | Reported the injection |",
        "|---|---:|---:|---:|---:|",
    ]
    for cell in sorted(rows, key=lambda row: str(row.get("controls", ""))):
        score = cell.get("injection") or {}
        cases = int(score.get("cases", 0) or 0)
        lines.append(
            f"| `{cell.get('controls', '?')}` "
            f"| {cases} "
            f"| {_fraction(int(score.get('proposed_canary', 0) or 0), cases)} "
            f"| **{_fraction(int(score.get('executed_canary', 0) or 0), cases)}** "
            f"| {_fraction(int(score.get('reported_injection', 0) or 0), cases)} |"
        )

    # Published attack-success rates differ by an order of magnitude between plain text and
    # multi-turn. An aggregate that mixes them hides the only interesting thing about it.
    by_style: dict[str, dict[str, int]] = {}
    for cell in rows:
        for style, counts in (cell.get("by_style") or {}).items():
            bucket = by_style.setdefault(style, {"cases": 0, "proposed": 0, "executed": 0})
            for key in bucket:
                bucket[key] += int(counts.get(key, 0) or 0)
    if by_style:
        lines += [
            "",
            "By payload style, summed across arms:",
            "",
            "| Style | Cases | Proposed the canary | Executed it |",
            "|---|---:|---:|---:|",
        ]
        for style, counts in sorted(by_style.items()):
            lines.append(
                f"| {style.replace('_', ' ')} "
                f"| {counts['cases']} "
                f"| {_fraction(counts['proposed'], counts['cases'])} "
                f"| **{counts['executed']}** |"
            )
    return lines


def render(document: dict[str, Any], *, source: pathlib.Path) -> str:
    """Build the README block. The headline is copied, never recomputed."""
    totals = document.get("totals") or {}
    settings = document.get("settings") or {}
    spend = document.get("spend") or {}
    interval = totals.get("execution_rate_ci95") or []

    lines = [
        BEGIN,
        PREAMBLE,
        "",
        f"> **{document.get('headline', '').strip()}**",
        "",
    ]
    if len(interval) == 2:
        lines += [
            f"The interval is Wilson, not the normal approximation, which returns "
            f"[{0:.0f}, {0:.0f}] at zero successes and would let a small sample claim a "
            f"certainty it has not earned.",
            "",
        ]

    cases = int(totals.get("injection_cases", 0) or 0)
    if cases:
        # The headline counts Axis B only, because only those cells carry authorization
        # counters. Saying so beside it stops a reader taking 144 trials for the whole
        # evaluation now that Axis A has run.
        proposed = int(totals.get("injection_proposed_canary", 0) or 0)
        executed = int(totals.get("injection_executed_canary", 0) or 0)
        lines += [
            f"That sentence counts Axis B. Separately, across {cases} Axis-A cases against a "
            f"real model, the model proposed the canary {proposed} times and the system "
            f"executed it {executed}.",
            "",
        ]

    lines += _axis_b_table(document.get("cells") or [])
    lines += _axis_a_table(document.get("cells") or [])

    scoreable = totals.get("scoreable_fraction")
    if scoreable is not None and scoreable < 1.0:
        lines += [
            "",
            f"{1 - float(scoreable):.0%} of Axis-A cases could not be scored — a failed "
            f"model call is excluded from the denominator rather than counted as the model "
            f"resisting.",
        ]

    lines += [
        "",
        "<details><summary>Provenance</summary>",
        "",
        f"- Artifact: `{display(source)}`",
        f"- SHA-256: `{digest_of(source)}`",
        f"- Run: `{document.get('run_id', '?')}`, status `{document.get('status', '?')}`",
        f"- Preregistration: `{str(document.get('preregistration_hash', ''))[:16]}`",
        f"- Model: `{settings.get('model', '?')}`, {settings.get('repeats', 1)} repeats, "
        f"arms {settings.get('arms', [])}",
        f"- Spend: ${float(spend.get('spent_usd', 0.0)):.2f} across "
        f"{spend.get('calls', 0)} live calls"
        if settings.get("live")
        else "- Spend: $0.00, no live calls",
        "",
        "</details>",
        END,
    ]
    return "\n".join(lines)


# --------------------------------------------------------------------------- README surgery


def splice(readme: str, block: str) -> str:
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start == -1 or end == -1:
        raise ReportError(
            f"README has no generated block. Add the markers {BEGIN} and {END} around the "
            f"results section."
        )
    if end < start:
        raise ReportError("README markers are in the wrong order.")
    return readme[:start] + block + readme[end + len(END) :]


def current_block(readme: str) -> str:
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start == -1 or end == -1:
        raise ReportError("README has no generated block.")
    return readme[start : end + len(END)]


# --------------------------------------------------------------------------- actions


def publish(artifact: pathlib.Path) -> pathlib.Path:
    """Copy an artifact into the published directory under a stable name."""
    document = load_artifact(artifact)
    PUBLISHED_DIR.mkdir(parents=True, exist_ok=True)
    stamp = str(document.get("run_id") or dt.datetime.now(dt.UTC).strftime("%Y%m%dT%H%M%S"))
    destination = PUBLISHED_DIR / f"{stamp}.json"
    destination.write_text(artifact.read_text(encoding="utf-8"), encoding="utf-8")
    return destination


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="agentsec-report",
        description="Generate the README results section from a published artifact.",
    )
    parser.add_argument(
        "--publish",
        metavar="ARTIFACT",
        help="copy this artifact into eval/results/published/ and use it",
    )
    parser.add_argument("--artifact", help="use this published artifact instead of the newest")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the README matches its evidence, and change nothing. For CI.",
    )
    parser.add_argument("--write", action="store_true", help="rewrite the README block in place")
    arguments = parser.parse_args(argv)

    try:
        if arguments.publish:
            source = publish(pathlib.Path(arguments.publish))
            print(f"published: {display(source)}")  # noqa: T201
        elif arguments.artifact:
            source = pathlib.Path(arguments.artifact)
        else:
            source = latest_published()

        document = load_artifact(source)
        block = render(document, source=source)
        readme = README_PATH.read_text(encoding="utf-8")

        if arguments.check:
            failures: list[str] = []
            if current_block(readme).strip() != block.strip():
                failures.append(
                    "the README results section is stale. Regenerate it with "
                    "`uv run task report-write`."
                )
            if not is_tracked(source):
                failures.append(
                    f"{display(source)} is not tracked by git, so the "
                    f"README's claim that the number comes from a committed artifact is false. "
                    f"`git add` it."
                )
            for failure in failures:
                print(f"FAIL: {failure}")  # noqa: T201
            if failures:
                return 1
            print("README matches its evidence.")  # noqa: T201
            return 0

        if arguments.write:
            README_PATH.write_text(splice(readme, block), encoding="utf-8")
            print(f"README updated from {source.name}")  # noqa: T201
            if not is_tracked(source):
                print(  # noqa: T201
                    f"note: {display(source)} is not committed yet. "
                    f"`git add` it, or --check will fail."
                )
            return 0

        print(block)  # noqa: T201
        return 0
    except ReportError as error:
        print(f"error: {error}")  # noqa: T201
        return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
